function setupBackToTop() {
  const button = document.querySelector(".back-to-top");
  if (!button) return;

  function updateVisibility() {
    button.classList.toggle("is-visible", window.scrollY > 600);
  }

  button.addEventListener("click", () => {
    window.scrollTo({ top: 0, behavior: "smooth" });
  });
  window.addEventListener("scroll", updateVisibility, { passive: true });
  updateVisibility();
}

function setLanguage(lang) {
  document.documentElement.lang = lang;
  localStorage.setItem("fjs-lang", lang);
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (translations[lang]?.[key]) node.textContent = translations[lang][key];
  });
  document.querySelectorAll("[data-i18n-rich]").forEach((node) => {
    const key = node.dataset.i18nRich;
    const value = translations[lang]?.[key];
    if (!value) return;
    node.replaceChildren(...value.split(/\n+/).map((paragraph) => paragraph.trim()).filter(Boolean).map((paragraph) => {
      const element = document.createElement("p");
      element.textContent = paragraph;
      return element;
    }));
  });
  document.querySelectorAll("[data-lang-option]").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.langOption === lang);
  });
  window.dispatchEvent(new CustomEvent("fjs-language-change", { detail: { lang } }));
}

function pickLocalized(value, lang) {
  if (!value) return "";
  if (typeof value === "string") return value.trim() ? value : "";
  return value[lang]?.trim?.() || value.ja?.trim?.() || value.en?.trim?.() || "";
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function renderNewsTitle(value) {
  const title = String(value || "").replace(/^●\s*/, "");
  return `<span class="news-title-dot" aria-hidden="true"></span><span>${escapeHtml(title)}</span>`;
}

function formatDate(value, lang) {
  const date = new Date(`${value}T00:00:00`);
  if (Number.isNaN(date.getTime())) return value;
  return new Intl.DateTimeFormat(lang === "ja" ? "ja-JP" : "en-US", {
    year: "numeric",
    month: "2-digit",
    day: "2-digit"
  }).format(date);
}

async function setupHomeNews() {
  const container = document.querySelector("[data-home-news]");
  if (!container) return;
  const lang = document.documentElement.lang || "ja";
  try {
    const response = await fetch("/data/posts.json", { cache: "no-store" });
    const data = await response.json();
    const posts = (data.posts || [])
      .filter((post) => post.status !== "draft")
      .sort((a, b) => String(b.date).localeCompare(String(a.date)))
      .slice(0, 3);
    container.innerHTML = posts.map((post) => `
      <article class="mini-news-card">
        <img src="${escapeHtml(sitePath(post.cover || "assets/home-hero-lifestyle.png"))}" alt="">
        <div>
          <time datetime="${escapeHtml(post.date)}">${escapeHtml(formatDate(post.date, lang))}</time>
          <h3>${renderNewsTitle(pickLocalized(post.title, lang))}</h3>
          <p>${escapeHtml(pickLocalized(post.excerpt, lang) || pickLocalized(post.body, lang))}</p>
        </div>
      </article>
    `).join("");
  } catch (error) {
    container.innerHTML = "";
  }
}

function setupHeroSlider() {
  const slider = document.querySelector(".hero-slider");
  if (!slider) return;

  const slides = [...slider.querySelectorAll(".hero-slide")];
  const dotsWrap = slider.querySelector("[data-hero-dots]");
  const prev = slider.querySelector("[data-hero-prev]");
  const next = slider.querySelector("[data-hero-next]");
  if (!slides.length || !dotsWrap) return;

  dotsWrap.innerHTML = slides.map((_, index) => `<button type="button" aria-label="Go to slide ${index + 1}" data-hero-dot="${index}"></button>`).join("");
  const dots = [...dotsWrap.querySelectorAll("[data-hero-dot]")];

  function showSlide(index) {
    currentHeroSlide = (index + slides.length) % slides.length;
    slides.forEach((slide, slideIndex) => slide.classList.toggle("is-active", slideIndex === currentHeroSlide));
    dots.forEach((dot, dotIndex) => dot.classList.toggle("is-active", dotIndex === currentHeroSlide));
  }

  function restartTimer() {
    window.clearInterval(heroTimer);
    heroTimer = window.setInterval(() => showSlide(currentHeroSlide + 1), 6800);
  }

  prev?.addEventListener("click", () => {
    showSlide(currentHeroSlide - 1);
    restartTimer();
  });
  next?.addEventListener("click", () => {
    showSlide(currentHeroSlide + 1);
    restartTimer();
  });
  dots.forEach((dot) => {
    dot.addEventListener("click", () => {
      showSlide(Number(dot.dataset.heroDot));
      restartTimer();
    });
  });

  let touchStart = 0;
  slider.addEventListener("touchstart", (event) => {
    touchStart = event.touches[0].clientX;
  }, { passive: true });
  slider.addEventListener("touchend", (event) => {
    const distance = event.changedTouches[0].clientX - touchStart;
    if (Math.abs(distance) > 42) {
      showSlide(currentHeroSlide + (distance < 0 ? 1 : -1));
      restartTimer();
    }
  }, { passive: true });

  showSlide(0);
  restartTimer();
}

function setupProductModal() {
  const modal = document.querySelector("[data-product-modal]");
  if (!modal) return;

  const image = modal.querySelector("[data-product-modal-image]");
  const title = modal.querySelector("[data-product-modal-title]");
  const body = modal.querySelector("[data-product-modal-body]");
  const link = modal.querySelector("[data-product-modal-link]");

  function closeModal() {
    modal.classList.remove("is-open");
    modal.setAttribute("aria-hidden", "true");
  }

  document.querySelectorAll(".product-preview").forEach((button) => {
    button.addEventListener("click", () => {
      const lang = document.documentElement.lang || "ja";
      const imageUrl = button.style.getPropertyValue("--product-image").replace(/^url\(['"]?/, "").replace(/['"]?\)$/, "");
      image.src = imageUrl;
      title.textContent = button.dataset[`productTitle${lang === "ja" ? "Ja" : "En"}`] || button.dataset.productTitleJa;
      body.textContent = button.dataset[`productBody${lang === "ja" ? "Ja" : "En"}`] || button.dataset.productBodyJa;
      link.href = sitePath(button.dataset.productLink || "/contact/");
      link.target = link.href.endsWith("/contact/") ? "_self" : "_blank";
      modal.classList.add("is-open");
      modal.setAttribute("aria-hidden", "false");
    });
  });

  modal.querySelectorAll("[data-product-close]").forEach((button) => button.addEventListener("click", closeModal));
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeModal();
  });
}

